// Rewrites the [[services.production.rewrites]] section of
// .replit-artifact/artifact.toml so every prerendered route is served from
// its own snapshot (rules/index.html …) instead of the SPA catch-all.
//
// Replit's static server applies rewrites in order and, with only a
// "/*" → "/index.html" rule, it hands the home page's HTML to every path —
// crawlers then see one thin page with canonical "/" everywhere. Listing the
// exact routes (both "/rules" and "/rules/") fixes that.
//
// There is deliberately NO "/*" catch-all. The client-only routes (game
// rooms, auth) are listed explicitly in SPA_ROUTES; any other URL matches no
// file and no rewrite, so the host answers with /404.html (built by
// vite.config.ts) instead of a 200 copy of the home page. A new client-only
// route in src/App.tsx must be added to SPA_ROUTES or it will 404 on reload.
//
//   node scripts/generate-artifact-rewrites.mjs
//
// Re-run whenever a route is added to src/content/prerenderRoutes.ts.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { PRERENDER_ROUTES } from "../src/content/prerenderRoutes.ts";

const here = path.dirname(fileURLToPath(import.meta.url));
const tomlPath = path.resolve(here, "../.replit-artifact/artifact.toml");

const START = "[[services.production.rewrites]]";
const original = readFileSync(tomlPath, "utf8");
const cut = original.indexOf(START);
if (cut === -1) throw new Error(`No ${START} block found in ${tomlPath}`);
const head = original.slice(0, cut).trimEnd();

// Routes rendered only in the browser. "*" matches the rest of the path and
// is only valid at the end of a pattern.
const SPA_ROUTES = ["/room/*", "/sign-in", "/sign-in/*", "/sign-up", "/sign-up/*"];

const blocks = [];
blocks.push(
  "# Generated by scripts/generate-artifact-rewrites.mjs from",
  "# src/content/prerenderRoutes.ts — do not edit the route list by hand.",
  "# Exact prerendered routes come first so each is served from its own",
  "# snapshot, then the client-only routes. There is no catch-all: unknown URLs",
  "# get /404.html.",
);
for (const route of PRERENDER_ROUTES) {
  if (route === "/") {
    // Explicit, so the home page never depends on the host's directory-index
    // handling now that there is no catch-all behind it.
    blocks.push("", START, 'from = "/"', 'to = "/index.html"');
    continue;
  }
  const target = `${route}/index.html`;
  for (const from of [route, `${route}/`]) {
    blocks.push("", START, `from = "${from}"`, `to = "${target}"`);
  }
}
for (const from of SPA_ROUTES) {
  blocks.push("", START, `from = "${from}"`, 'to = "/index.html"');
}
blocks.push("");

writeFileSync(tomlPath, `${head}\n\n${blocks.join("\n")}`);
console.log(`wrote ${PRERENDER_ROUTES.length} routes (${(PRERENDER_ROUTES.length - 1) * 2 + 1} rewrites) + ${SPA_ROUTES.length} client-only routes to ${path.relative(process.cwd(), tomlPath)}`);

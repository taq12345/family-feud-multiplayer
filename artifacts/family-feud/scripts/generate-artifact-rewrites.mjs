// Rewrites the [[services.production.rewrites]] section of
// .replit-artifact/artifact.toml so every prerendered route is served from
// its own snapshot (rules/index.html …) instead of the SPA catch-all.
//
// Replit's static server applies rewrites in order and, with only the
// "/*" → "/index.html" rule, it hands the home page's HTML to every path —
// crawlers then see one thin page with canonical "/" everywhere. Listing the
// exact routes first (both "/rules" and "/rules/") fixes that; the catch-all
// stays last for game rooms, auth and unknown URLs.
//
//   node scripts/generate-artifact-rewrites.mjs
//
// Re-run whenever a route is added to src/content/prerenderRoutes.ts.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { PRERENDER_ROUTES } from "../src/content/prerenderRoutes.ts";

const here = path.dirname(fileURLToPath(import.meta.url));
const tomlPath = path.resolve(here, "../.replit-artifact/artifact.toml");

const START = "[[services.production.rewrites]]";
const original = readFileSync(tomlPath, "utf8");
const cut = original.indexOf(START);
if (cut === -1) throw new Error(`No ${START} block found in ${tomlPath}`);
const head = original.slice(0, cut).trimEnd();

const blocks = [];
blocks.push(
  "# Generated by scripts/generate-artifact-rewrites.mjs from",
  "# src/content/prerenderRoutes.ts — do not edit the route list by hand.",
  "# Exact prerendered routes come first so each is served from its own",
  "# snapshot; the trailing catch-all keeps the SPA working for everything else.",
);
for (const route of PRERENDER_ROUTES) {
  if (route === "/") continue; // "/" already resolves to /index.html
  const target = `${route}/index.html`;
  for (const from of [route, `${route}/`]) {
    blocks.push("", START, `from = "${from}"`, `to = "${target}"`);
  }
}
blocks.push("", START, 'from = "/*"', 'to = "/index.html"', "");

writeFileSync(tomlPath, `${head}\n\n${blocks.join("\n")}`);
console.log(`wrote ${PRERENDER_ROUTES.length - 1} routes (${(PRERENDER_ROUTES.length - 1) * 2} rewrites) + catch-all to ${path.relative(process.cwd(), tomlPath)}`);
